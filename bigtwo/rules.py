"""大老二規則設定（明星三缺一，依遊戲內規則說明 2026-10-16）。

確定的（規則說明頁）：
- 持有梅花 3 的人先出，逆時針輪流；其他人要出同樣牌型且比上一家大，時間到算 PASS。
- 點數 2 > A > K > … > 3，花色 黑桃 > 紅心 > 方塊 > 梅花，先比點數再比花色。
- 牌型：單張、一對、三條、順子、葫蘆、鐵支（四張＋一張任意牌）、同花順。
  順子 A2345 最小、23456 最大；同點數順子比最大那張的花色。葫蘆比三張的點數。
- 特殊加倍（輸家負分再加一次本局倍率）：剩超過 9 張、手上有 2、13 張都沒出、
  贏家最後一手含梅花 3、有發牌權的人一路出完沒讓別人出過任何牌（滿貫全壘打）。

使用者確認（10/16）：
- 鐵支、同花順可以壓單張、對子、三條。
- 第一手不一定要含梅花 3（梅花 3 留到最後出完還有「最後脫手3」加倍）。
- PASS 之後同一輪還能再出。
- 加倍是一項乘一次本局倍率：剩 11 張又有 2 → 11 × 2 × 2。

錄影確認（bigtwo_train/Desktop 2026.10.16 - 18.22.28.03.mp4）：
- 牌桌資訊「每張5分、可打三條 / 梅花3不需先出 / 梅花3最後出加倍」，一場 4 局，每手 8 秒。
- 發牌時顯示「此局加倍項目 2 倍」＝本局倍率。結算：自己剩 3 張 −30（3×5 分×2，贏家梅花三脫手）、
  剩 7 張有 2 −140（7×5×2×2）、贏家 +200——加倍項目是相乘。
- 開局換三張：每人選 0～3 張蓋著放到中間，全部收在一起洗過再發回，每人拿回同樣張數
  （影片中自己換出 5♣8♦、拿回 3♥4♦）。遊戲提示「交換梅花3會失去出牌權」。
- 出牌順序 上家 → 自己 → 下家（右）→ 對家：座位 0 是自己時 1 是右邊。
- 沒有「同花」（五張同花色但不連續）；`flush_enabled` 留給別的玩法。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Rules:
    flush_enabled: bool = False
    bombs_beat_smaller: bool = True
    first_must_include_club3: bool = False
    pass_locks_out: bool = False
    rate: int = 2           # 本局倍率：輸家扣 張數 × rate^加倍項數
    swap: bool = True       # 開局換三張


DEFAULT_RULES = Rules()
